export function findCard(id: string): CardDef | undefined {
  return cards.find((c) => c.id === id);
}

/** スターター以外の報酬プール */
const STARTER_IDS = new Set(['ST-REPORT', 'ST-REVIEW', 'ST-REPRO', 'ST-EXPLORE']);
export const rewardPool = cards.filter((c) => !STARTER_IDS.has(c.id));

export function poolByRarity(rarity: CardRarity): CardDef[] {
  return rewardPool.filter((c) => c.rarity === rarity);
}
